function P = setup_paths()
%SETUP_PATHS Define folders and add the analysis code to the MATLAB path.
%   P = SETUP_PATHS() returns a struct with the repository, data and output
%   folders, and adds the repository code to the MATLAB path.
%
%   By default the data are expected in <repo>/data (download link in
%   README.md). To use another location, copy config_local_example.m to
%   config_local.m and set cfg.dataRoot. config_local.m is ignored by git.

P.repo = fileparts(mfilename('fullpath'));

cfg = struct();
if exist(fullfile(P.repo, 'config_local.m'), 'file')
    cfg = config_local();
end
if isfield(cfg, 'dataRoot')
    P.data = cfg.dataRoot;
else
    P.data = fullfile(P.repo, 'data');
end
if isfield(cfg, 'mapseqRawRoot')
    P.mapseqRaw = cfg.mapseqRawRoot;      % MAPseq pipeline output (not public)
end
if ~exist(P.data, 'dir')
    error('setup_paths:noData', ...
        'Data folder not found: %s\nSee README.md for the download link.', P.data);
end

% Code, atlas and shared resource files
P.functions = fullfile(P.repo, 'functions');
P.atlas     = fullfile(P.repo, 'atlas');
P.resources = fullfile(P.repo, 'resources');   % e.g. color_schemes.mat
P.external  = fullfile(P.repo, 'external');

addpath(genpath(P.functions));
addpath(P.atlas);
addpath(P.resources);
addpath(genpath(fullfile(P.external, 'allenCCF')));
addpath(genpath(fullfile(P.external, 'MousePFC_ResearchSynthesis')));
addpath(genpath(fullfile(P.external, 'Registration_Segmentation_KF')));  % needed to read subAtlas.mat

% Data and output
P.brainData = P.data;                               % per-experiment <exp>.mat files
P.mapseq    = fullfile(P.data, 'mapseq');           % MAPseq barcode matrices (.xlsx)
P.processed = fullfile(P.data, 'processedTable');   % generated by the preprocessing scripts
P.output    = fullfile(P.repo, 'output');           % figures and exported tables
if ~exist(P.processed, 'dir'), mkdir(P.processed); end
if ~exist(P.output, 'dir'),    mkdir(P.output);    end
end
